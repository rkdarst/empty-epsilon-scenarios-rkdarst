#!/usr/bin/env bash
# ee_func.sh - the real test: boot a scenario headless UNPAUSED and let the
# mission actually run, with a self-driving assertion timeline appended to it.
# Nothing in the scenario needs test hooks: the runner builds
#
#     [settings prelude] + <scenario.lua> + lib/autotest.lua + <driver.lua>
#
# as one file in a throwaway HOME (EE concatenates every .lua in the scripts
# dir into a single chunk, and the whole scenario is one anonymous Lua chunk,
# so its `local` helpers stay visible to the driver).
#
# Usage: ee_func.sh path/to/scenario_NN_name.lua [cmds.txt]
#   AUTOTEST=path.lua   driver to append (default: <root>/tests/<name>.autotest.lua,
#                       AUTOTEST=none disables the append -> plain long boot)
#   SCEN_PRE=path.lua   file concatenated BEFORE the scenario
#   EE_SETTINGS="K=V;K2=V2"   force Setting[...] values headless (EE has no CLI
#                       plumbing for them - they only arrive from the GUI)
#   RUNTIME=60   game seconds to let the timeline play out
#   SMOKE_TIMEOUT=40  load wait   GAP=4  spacing for [cmds.txt] console lines
# All other args are passed through to the game binary.
# Exit: 0 all assertions passed | 1 failures / driver never finished | 2 setup | 4 port busy
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/ee_env.sh"

SCEN="${1:?usage: ee_func.sh <scenario.lua> [cmds.txt]}"
ee_guard_port
shift || true
[[ -f "$SCEN" ]] || { echo "not a file: $SCEN" >&2; exit 2; }
BASE="$(basename "$SCEN")"
ee_locate || exit 2

CMDS="${1:-}"
RUNTIME="${RUNTIME:-60}"; TIMEOUT="${SMOKE_TIMEOUT:-40}"; GAP="${GAP:-4}"

name="${BASE%.lua}"
BOOT_ONLY=0
if [[ "${AUTOTEST:-}" == none ]]; then
    DRIVER=""; BOOT_ONLY=1                      # deliberate: just let it run
else
    DRIVER="${AUTOTEST:-$EE_REPO/tests/$name.autotest.lua}"
fi
if [[ -n "$DRIVER" && ! -f "$DRIVER" ]]; then
    echo "NOTE: no autotest driver at $DRIVER - booting and idling only" >&2
    DRIVER=""
fi

EEHOME="$(mktemp -d)"; trap 'rm -rf "$EEHOME" "$EEHOME.fifo"' EXIT
mkdir -p "$EEHOME/.emptyepsilon/scripts" "$EEHOME/run"

# --- assemble the runnable file ------------------------------------------------
catpart=()
if [[ -n "${SCEN_PRE:-}" ]]; then
    [[ -f "$SCEN_PRE" ]] || { echo "not a file: SCEN_PRE=$SCEN_PRE" >&2; exit 2; }
    catpart+=("$SCEN_PRE")
fi
if [[ -n "${EE_SETTINGS:-}" ]]; then
    # getScenarioSetting() is the only way a scenario learns its Setting[...]
    # values and headless EE never gets them (GUI-only), so shadow the reader
    # BEFORE the scenario's top level (load time) runs.
    PRE="$EEHOME/settings_pre.lua"
    {
        echo "-- generated by ee_func.sh from EE_SETTINGS=$EE_SETTINGS"
        echo "do"
        echo "  local ee_real, ee_ov = getScenarioSetting, {"
        IFS=';' read -ra kv <<< "$EE_SETTINGS"
        for e in "${kv[@]}"; do
            [[ "$e" == *=* ]] || continue
            printf '    ["%s"] = "%s",\n' "${e%%=*}" "${e#*=}"
        done
        echo "  }"
        echo "  getScenarioSetting = function(k) local v = ee_ov[k]"
        echo "    if v ~= nil then return v end return ee_real(k) end"
        echo "end"
    } > "$PRE"
    catpart+=("$PRE")
fi
catpart+=("$SCEN")
if [[ -n "$DRIVER" ]]; then
    catpart+=("$EE_PKG_DIR/lib/autotest.lua")
    catpart+=("$DRIVER")
fi
cat "${catpart[@]}" > "$EEHOME/.emptyepsilon/scripts/$BASE"

for d in resources scripts packs; do [[ -e "$EE_DATA/$d" ]] && ln -sfn "$EE_DATA/$d" "$EEHOME/run/$d"; done

# --- run -----------------------------------------------------------------------
FIFO="$EEHOME.fifo"; mkfifo "$FIFO" || exit 2
cd "$EEHOME/run"
HOME="$EEHOME" EE_CONF_DIR="$EEHOME/.emptyepsilon" \
LD_LIBRARY_PATH="${EE_LD}${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
SDL_VIDEODRIVER=dummy SDL_AUDIODRIVER=dummy \
${EE_NS[@]+"${EE_NS[@]}"} \
"$EE_BIN" headless="$BASE" server_port="${SMOKE_PORT:-35781}" < "$FIFO" > ee.log 2>&1 &
pid=$!
exec 3>"$FIFO"
loaded=0
for ((t=0; t<TIMEOUT*2; t++)); do
    kill -0 "$pid" 2>/dev/null || { echo "ERROR: game exited early (segfault? port busy?)"; break; }
    grep -q "Load script: $BASE" ee.log && { loaded=1; break; }
    sleep 0.5
done
[[ $loaded -eq 1 ]] || { tail -30 ee.log; exit 1; }

if [[ -n "$CMDS" && -f "$CMDS" ]]; then         # best effort: headless stdin may
    while IFS= read -r cmd; do                  # be ignored by the engine
        [[ -z "$cmd" || "$cmd" == \#* ]] && continue
        echo "$cmd" >&3 || break
        sleep "$GAP"
    done < "$CMDS"
fi

DONE_RE='EE-AUTOTEST done|LC-AUTOTEST done|mission complete - victory declared'
FAIL_RE='EE-ASSERT FAIL|EE-ASSERT ERROR|LC-ASSERT FAIL|LC-ASSERT ERROR'
for ((t=0; t<RUNTIME*2; t++)); do
    kill -0 "$pid" 2>/dev/null || break
    grep -qaE "$DONE_RE" ee.log && { sleep 3; break; }   # let stragglers log
    sleep 0.5
done
kill -9 "$pid" 2>/dev/null; wait "$pid" 2>/dev/null

echo "--- script output ---------------------------------------------------------"
grep -aE 'LUA:|ERROR' ee.log | sed -E 's/^(INFO: )?LUA:/LUA:/'
if grep -qaE "$FAIL_RE" ee.log; then
    echo "RESULT: FAILURES PRESENT"; exit 1
elif grep -qaE "$DONE_RE" ee.log; then
    echo "RESULT: AUTOTEST PASSED"; exit 0
fi
echo "RESULT: autotest driver never finished (or is absent) - check script output"; exit 1
